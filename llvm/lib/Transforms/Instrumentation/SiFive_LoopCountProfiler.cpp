namespace {
// Insert instrumentation in header and in exit block of loop
class InsertCounter {
  // GlobalVariables declared in this module
  GlobalVariable *Anchor = nullptr;

  // Initialize the loopsname array
  std::vector<Constant *> LoopNamesV;

  // Map Loop with their ID
  std::map<Loop *, uint64_t> LoopsMap;
  uint64_t Iter = 0;

  // Wrapper of string type
  StructType *StringWrapperTy;

  // number of loops in this module
  uint32_t NumLoops = 0;

public:
  InsertCounter(Module &M) {
    // Initial helper types
    StringWrapperTy = StructType::create(M.getContext());
    Type *CharPtrTy = PointerType::getUnqual(M.getContext());
    StringWrapperTy->setBody(CharPtrTy);
  }
  bool runOnModule(Module &M, llvm::function_ref<LoopInfo &(Function &)> GetLI);
  bool declareVars(Module &M);
  unsigned generateLoopNames(Module &M, Function &F, LoopInfo &LI);
  unsigned generateSubLoopNames(Module &M, Function &F, Loop *L);
  void collectSubLoops(std::vector<Loop *> &Cur, std::vector<Loop *> &Loops);
};

class InsertCounterOnLoop {
  Loop *L = nullptr;
  Module *M = nullptr;
  uint64_t Iter;

  // The insertion Blocks for the Counter
  std::vector<Instruction *> ExitsFirstInsts;

  // Temporary Counter which will alloca in the preheader
  AllocaInst *LocalCounter;
  GlobalVariable *Anchor;

public:
  InsertCounterOnLoop(Loop *L, Module *M, uint64_t Iter,
                      AllocaInst *LocalCounter, GlobalVariable *Anchor)
      : L(L), M(M), Iter(Iter), LocalCounter(LocalCounter), Anchor(Anchor){};

  void run();

  // Collect BasicBlocks to insert Counters
  void collectInsertBlocks();

  // Insert Counter on BBs
  void insertExitCounter(Instruction *);
  void insertLocalCounter(Instruction *);
};

} // namespace

// Get the name of loop from debug information.
static Constant *getLoopName(Module &M, Function &F, Loop *L) {
  if (L->getStartLoc().get()) {
    return ConstantDataArray::getString(
        M.getContext(),
        (L->getHeader()->getName() + "-" + F.getName() + ", " +
         cast<DIScope>(L->getStartLoc().getScope())->getFilename() + ":" +
         Twine(L->getStartLoc().getLine()))
            .str());
  } else {
    return ConstantDataArray::getString(M.getContext(),
                                        (L->getHeader()->getName() + "-" +
                                         F.getName() + ", " + "unknown:unknown")
                                            .str());
  }
}

PreservedAnalyses LoopCountProfilerPass::run(Module &M,
                                             ModuleAnalysisManager &AM) {
  InsertCounter IC(M);

  auto GetLI = [&](Function &F) -> LoopInfo & {
    auto &FAM =
        AM.getResult<FunctionAnalysisManagerModuleProxy>(M).getManager();
    return FAM.getResult<LoopAnalysis>(F);
  };
  if (IC.runOnModule(M, GetLI))
    return PreservedAnalyses::none();
  else
    return PreservedAnalyses::all();
}

unsigned InsertCounter::generateSubLoopNames(Module &M, Function &F, Loop *L) {
  unsigned Count = L->getSubLoops().size();
  // Generate Loop Names
  for (Loop *SubL : L->getSubLoops()) {
    Constant *ConstantStr = getLoopName(M, F, SubL);
    GlobalVariable *tmpString =
        new GlobalVariable(M, ConstantStr->getType(), true,
                           GlobalValue::PrivateLinkage, ConstantStr);
    LoopNamesV.push_back(ConstantStruct::get(StringWrapperTy, tmpString));
    LoopsMap.insert(std::make_pair(SubL, Iter++));
    // Traverse subLoops
    Count += generateSubLoopNames(M, F, SubL);
  }

  return Count;
}

// Calculate how many loops in this module and the array size need to declare
// and generate loop names
unsigned InsertCounter::generateLoopNames(Module &M, Function &F,
                                          LoopInfo &LI) {
  unsigned Count = LI.getTopLevelLoops().size();
  // Generate Loop Names
  for (Loop *L : LI) {
    Constant *ConstantStr = getLoopName(M, F, L);
    GlobalVariable *tmpString =
        new GlobalVariable(M, ConstantStr->getType(), true,
                           GlobalValue::PrivateLinkage, ConstantStr);
    LoopNamesV.push_back(ConstantStruct::get(StringWrapperTy, tmpString));
    LoopsMap.insert(std::make_pair(L, Iter++));
    // Iterate subLoops
    Count += generateSubLoopNames(M, F, L);
  }

  //  If no loops in code then no need to instrument function code
  if (Count == 0) {
    LLVM_DEBUG(dbgs() << "No loops in Function" << F << "\n");
  }
  return Count;
}

// Declare Counters with the proper length
bool InsertCounter::declareVars(Module &M) {

  // Declare a global extern variable to load the runtime library.
  //
  // This variable will be unset when linking, which will force linker
  // load the loopprofile runtime library.
  //
  // We use the same method as llvm InstProfile.
  (void)new GlobalVariable(M, IntegerType::get(M.getContext(), 32), false,
                           GlobalValue::ExternalLinkage, 0,
                           "__llvm_loop_profile_runtime");

  // Declare Global Array to Stor Counter for Loop exit
  ArrayType *IntNumLoops =
      ArrayType::get(IntegerType::get(M.getContext(), 64), NumLoops);

  // Exit Counter
  GlobalVariable *ExitCounter = new GlobalVariable(
      M, IntNumLoops, false, GlobalValue::PrivateLinkage, 0, "ExitCounter");
  ConstantAggregateZero *ConstZeroIntArray =
      ConstantAggregateZero::get(IntNumLoops);
  ExitCounter->setSection("__llvm_loop_prof_data");
  ExitCounter->setInitializer(ConstZeroIntArray);

  // Declare Global Array to Store Counter for Loop latch (trip count)
  GlobalVariable *LatchCounter = new GlobalVariable(
      M, IntNumLoops, false, GlobalValue::PrivateLinkage, 0, "LatchCounter");
  LatchCounter->setSection("__llvm_loop_prof_data");
  LatchCounter->setInitializer(ConstZeroIntArray);

  // Declare Global Array to Store Counter for Loop min Latch count.
  Constant *IntMaximum = Constant::getIntegerValue(
      IntegerType::get(M.getContext(), 64), APInt::getSignedMaxValue(64));
  std::vector<Constant *> VArray(NumLoops, IntMaximum);
  Constant *IntMaximumArray = ConstantArray::get(IntNumLoops, VArray);
  GlobalVariable *MinLatchCounter = new GlobalVariable(
      M, IntNumLoops, false, GlobalValue::PrivateLinkage, 0, "MinLatchCounter");
  MinLatchCounter->setSection("__llvm_loop_prof_data");
  MinLatchCounter->setInitializer(IntMaximumArray);

  // Declare Global Array to Store Counter for max latch count.
  GlobalVariable *MaxLatchCounter = new GlobalVariable(
      M, IntNumLoops, false, GlobalValue::PrivateLinkage, 0, "MaxLatchCounter");
  MaxLatchCounter->setSection("__llvm_loop_prof_data");
  MaxLatchCounter->setInitializer(ConstZeroIntArray);

  // Declare Global Array to Store Counter for max latch count.
  GlobalVariable *ExecutedFlag = new GlobalVariable(
      M, IntNumLoops, false, GlobalValue::PrivateLinkage, 0, "ExecutedFlag");
  ExecutedFlag->setSection("__llvm_loop_prof_data");
  ExecutedFlag->setInitializer(ConstZeroIntArray);

  // Some helper Types
  ArrayType *StrPtrNumLoops = ArrayType::get(StringWrapperTy, NumLoops);

  // The global array which will store the LoopNames.
  GlobalVariable *LoopNames = new GlobalVariable(
      M, StrPtrNumLoops, false, GlobalValue::PrivateLinkage, 0, ".loopnames");
  LoopNames->setSection("__llvm_loop_prof_data");
  Constant *LoopNamesArr = ConstantArray::get(StrPtrNumLoops, LoopNamesV);
  LoopNames->setInitializer(LoopNamesArr);

  // Define a struct which contain pointers to the metadata of loop profiling
  // separate in different file. This struct help us collect the information at
  // runtime.
  PointerType *IntArrayPoIntType = PointerType::get(IntNumLoops, 0);
  PointerType *StrArrayPoIntType = PointerType::get(StrPtrNumLoops, 0);
  PointerType *PointerPoIntType = PointerType::get(
      PointerType::get(IntegerType::get(M.getContext(), 8), 0), 0);
  IntegerType *IntType = IntegerType::get(M.getContext(), 32);
  StructType *St = StructType::create(M.getContext(), "loop_profile_loc");

  // Members of the Anchor
  // {ExitCounter, ExitingCounters (deprecated), latchConters,
  // MinLatchCounters, MaxLatchCounters, LoopNames,
  // loopCounts in Module, Execcuted Flag (deprecated)}
  Type *members[8] = {IntArrayPoIntType, IntArrayPoIntType, IntArrayPoIntType,
                      IntArrayPoIntType, IntArrayPoIntType, StrArrayPoIntType,
                      IntType,           PointerPoIntType};

  St->setBody(members, /*pack=*/false);
  Anchor = new GlobalVariable(M, St, false, GlobalValue::PrivateLinkage, 0,
                              "Anchor");
  Anchor->setSection("__llvm_loop_prof");
  Constant *NumLoopsConst =
      ConstantInt::get(IntegerType::get(M.getContext(), 32), NumLoops);
  Constant *AnchorInit = ConstantStruct::get(
      St, ExitCounter, LatchCounter, LatchCounter, MinLatchCounter,
      MaxLatchCounter, LoopNames, NumLoopsConst, ExecutedFlag);
  Anchor->setInitializer(AnchorInit);

  // Declare min/max caculte function provided by Runtime
  Function *MinMaxFunc;
  Type *info_collection_args[3] = {
      PointerType::get(IntegerType::get(M.getContext(), 64), 0),
      IntegerType::get(M.getContext(), 32),
      IntegerType::get(M.getContext(), 64)};
  FunctionType *info_collection_type = FunctionType::get(
      IntegerType::get(M.getContext(), 32), info_collection_args, false);
  MinMaxFunc =
      Function::Create(info_collection_type, GlobalValue::ExternalLinkage,
                       "__loop_prof_info_collection", &M);
  MinMaxFunc->setCallingConv(CallingConv::C);

  return true;
}

#ifndef NDEBUG
/// \return string containing a file name and a line # for the given loop.
static std::string getDebugLocString(const Loop *L) {
  std::string Result;
  if (L) {
    raw_string_ostream OS(Result);
    if (const DebugLoc LoopDbgLoc = L->getStartLoc())
      LoopDbgLoc.print(OS);
    else
      // Just print the module name.
      OS << L->getHeader()->getParent()->getParent()->getModuleIdentifier();
    OS.flush();
  }
  return Result;
}
#endif

void InsertCounterOnLoop::run() {

#ifndef NDEBUG
  const std::string DebugLocStr = getDebugLocString(L);
#endif /* NDEBUG */
  LLVM_DEBUG(dbgs() << "LoopCountProfiler: Checking a loop in '"
                    << L->getHeader()->getParent()->getName() << "' from "
                    << DebugLocStr << "\n");

  collectInsertBlocks();

  // Insert the runtime function in the exit block which
  // will count the the exit count
  for (Instruction *e : ExitsFirstInsts) {
    insertExitCounter(e);
  }
  // Insert the trip count counter in the header block
  insertLocalCounter(L->getHeader()->getFirstNonPHI());
}

void InsertCounterOnLoop::insertLocalCounter(Instruction *e) {
  IRBuilder<> IRB(e);

  // Tmp latch count + 1, we will write back the latch count in Exit block
  LoadInst *TmpCounter =
      IRB.CreateLoad(IntegerType::get(M->getContext(), 64), LocalCounter);
  Value *IncTmpCount = IRB.CreateAdd(
      TmpCounter, ConstantInt::get(M->getContext(), APInt(64, 1)));
  IRB.CreateStore(IncTmpCount, LocalCounter);
}

void InsertCounterOnLoop::insertExitCounter(Instruction *E) {
  IRBuilder<> IRB(E);

  // Load local counter
  LoadInst *Count =
      IRB.CreateLoad(IntegerType::get(M->getContext(), 64), LocalCounter);

  // call the runtime function `collect_info(anchor, iter, LatchCounter)`
  std::vector<Value *> MinMaxArgs{
      Anchor, ConstantInt::get(M->getContext(), APInt(32, Iter)), Count};
  Function *InfoCollect = M->getFunction("__loop_prof_info_collection");
  IRB.CreateCall(InfoCollect, MinMaxArgs);
  IRB.CreateStore(ConstantInt::get(M->getContext(), APInt(64, 0)),
                  LocalCounter);
}

// Collect the instruction we will insert the timer behind it
void InsertCounterOnLoop::collectInsertBlocks() {
  SmallVector<BasicBlock *, 8> Exits;

  L->getExitBlocks(Exits);

  // Iterate over each created exit block and insert them in a vector
  for (BasicBlock *e : Exits) {
    if (e->isLandingPad() || e->isEHPad())
      continue;
    ExitsFirstInsts.push_back(e->getFirstNonPHI());
  }
}

void InsertCounter::collectSubLoops(std::vector<Loop *> &Cur,
                                    std::vector<Loop *> &Loops) {
  if (Cur.size() == 0) {
    return;
  }
  for (Loop *L : Cur) {
    for (Loop *Sub : L->getSubLoops()) {
      std::vector<Loop *> Next;
      Loops.push_back(Sub);
      Next.push_back(Sub);
      collectSubLoops(Next, Loops);
    }
  }
}

bool InsertCounter::runOnModule(
    Module &M, llvm::function_ref<LoopInfo &(Function &)> GetLI) {
  // Count how many loops in this module
  for (Function &F : M) {
    // Skip function declaration in the module
    if (F.isIntrinsic() || F.isDeclaration()) {
      continue;
    }
    NumLoops += generateLoopNames(M, F, GetLI(F));
  }
  NumOfLoops = NumLoops;
  // No loop in the module
  if (NumLoops <= 0)
    return false;

  // Declare counters
  declareVars(M);

  for (Function &F : M) {
    // Skip function declaration in the module
    if (F.isIntrinsic() || F.isDeclaration()) {
      continue;
    }

    LoopInfo &LI = GetLI(F);
    std::vector<Loop *> Loops;
    std::vector<Loop *> Cur;
    std::vector<AllocaInst *> LocalCounters;

    // Collect all subLoops in the Module
    Loops.insert(Loops.end(), LI.getTopLevelLoops().begin(),
                 LI.getTopLevelLoops().end());
    Cur.insert(Cur.end(), LI.getTopLevelLoops().begin(),
               LI.getTopLevelLoops().end());
    collectSubLoops(Cur, Loops);

    // Insert alloca in the funciton entry as loacl counters
    IRBuilder<> InsertAlloca(F.getEntryBlock().getFirstNonPHI());

    for (Loop *L : Loops) {

      BasicBlock *Header = L->getHeader();
      // Skip if the loop is not counted before
      if (LoopsMap.find(L) == LoopsMap.end())
        continue;

      // Skip if header is not exist
      if (!Header)
        continue;

      // Allocate local counters in the funciton entry
      AllocaInst *LocalCounter =
          InsertAlloca.CreateAlloca(IntegerType::get(M.getContext(), 64));
      InsertAlloca.CreateStore(
          ConstantInt::get(IntegerType::get(M.getContext(), 64), 0),
          LocalCounter);

      InsertCounterOnLoop RunOnLoop(L, &M, LoopsMap[L], LocalCounter, Anchor);
      RunOnLoop.run();
    }
  }

  return true;
}

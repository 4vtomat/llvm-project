// This file instruments the code for each loop to calculate the run-time
// information the number of times the whole loop executes and the trip count
// of each loop.
//
// In Each module, we will insert following arrays to storage profile data.
// `.loopnames`: Array of loops names generated by debug infomation.
// `ExitCounter`: Array of whole loop executed.
// `LatchCounter`: Array of trip count.
// `Min/MaxLatchCounter`: Array of min/max trip count.
// `ExecutedFlag`: Array of executed flags.
//
// To collect information cross modules whend linking, we create `Anchor`s
// to link the local information together in the special section called
// `__llvm_loop_prof`.
//
// |--------|--------|--------|--------|
// |Anchor 0|Anchor 1|Anchor 2|Anchor 3| ...
// |--------|--------|--------|--------|
//    | |-----|----------------|----------|----------|-------------|
//    ->|Name |#loops in module|Exit count|Trip count|Min/Max count|
//      |-----|----------------|----------|----------|-------------|
//
// This instrumentation will affect to the loops and insert profile counters
// and functions in the loops. The runtime function will help us to update
// loop count and the trip count.
// Before:
//  Func(){
//   Header:
//     ...
//   Latch:
//     ...
//   Exiting:
//     ...
//   Exit:
//     ...
//  }
//
// After:
//  Func(){
//    alloc local_counter;
//
//    Header:
//      local_counter += 1;
//      ...
//    Latch:
//      ...
//    Exiting:
//      ...
//    Exit:
//      call @__loop_prof_info_collection(Anchor, LoopID, local_countre);
//      local_counter = 0;
//      ...
//  }
//
// Not all loops we can instrument, following types of loop we will skip.
//  1. Loops without header or exit block.
//  2. Exit block of the loop is LandingPad or EHPad
//
// NOTE:
//  1. To get the correct loop name, please add `-g` when compiling.
//  2. The profile output can be control by `LOOP_PROFILE=<profile output>`
//     and the default output file name is `loopProfile.output`.
//  3. This profiler only provide single thread profiling.
//===----------------------------------------------------------------------===//


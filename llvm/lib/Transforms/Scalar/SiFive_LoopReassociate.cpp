#define DEBUG_TYPE "loop-reassociate"

STATISTIC(NumReassociatedReductions, "Number of reassociated reductions");

static cl::opt<bool>
    EnableLoopReassociate("sifive-loop-reassociate", cl::Hidden, cl::init(true),
                          cl::desc("Reassociate operations across loops"));

/// Check that reduce intrinsic that following properties:
/// * has computation of its operand within the same BB
/// * is used in computation chain with homogeneous instructions,
/// * forms loop carried dependencies within the same loop as the reduce
///   intrinsic is,
/// * used outside by a phi with a single incoming value.
///
/// In this case it can be optimized by generating accumulator vector and moving
/// reduce intrinsic to the phi in exit block.
///
/// TODO: Relax first constrain by doing extra analysis on how incoming value is
/// defined and used. For example
///
/// for () {
///   r = 0;
///   for () {
///     r += ;
///   }
/// }
///
/// and
///
/// r = 0;
/// for () {
///   for () {
///     r += ;
///   }
/// }
///
/// have almost identical vector code generated by loop vectorizer. Analyzing
/// starting value of `r` can allow hoisting of a reduce intrinsic generated by
/// the loop vectorizer.
static bool canSimplifyInLoopReduction(Instruction *I, PHINode **LastUse,
                                       LoopInfo &LI) {
  using namespace PatternMatch;

  *LastUse = nullptr;
  auto *Reduce = dyn_cast<CallInst>(I);
  if (!Reduce || !Reduce->hasOneUse())
    return false;

  bool IsFPReduce;
  switch (Reduce->getIntrinsicID()) {
  case Intrinsic::vector_reduce_add:
    IsFPReduce = false;
    break;
  case Intrinsic::vector_reduce_fadd:
    IsFPReduce = true;
    break;
  default:
    return false;
  }

  LLVM_DEBUG(dbgs() << "LoopReassociate: analyzing " << *I << '\n');

  if (IsFPReduce) {
    FastMathFlags FMF = Reduce->getFastMathFlags();
    if (!FMF.allowReassoc()) {
      LLVM_DEBUG(dbgs() << "LoopReassociate: cannot simplify it as it does not "
                           "allow reassociation\n");
      return false;
    }
  }

  auto GetFirstNonSupportedInstruction =
      [IsFPReduce](Instruction *I) -> Instruction * {
    FastMathFlags ReassocFMF;
    ReassocFMF.setAllowReassoc();
    do {
      I = I->user_back();

      // Expect a chain of add or fadd instructions depending on type a
      // reduction. The `fadd` instruction should also allow fp reassociation
      if ((!IsFPReduce && !match(I, m_Add(m_Value(), m_Value()))) ||
          (IsFPReduce && !match(I, m_CombineAnd(m_FAdd(m_Value(), m_Value()),
                                                m_FMF(ReassocFMF)))))
        return nullptr;
    } while (I->hasOneUse());
    return I;
  };

  // TODO: Support fsub and sub instructions. See GB5/312
  if ((I = GetFirstNonSupportedInstruction(I)) == nullptr) {
    LLVM_DEBUG(
        dbgs()
        << "LoopReassociate: cannot simplify it due to unexpected use\n");
    return false;
  }

  const Loop *L = LI.getLoopFor(Reduce->getParent());
  if (L->contains(I)) {
    // It's possible that `I` is cross-iteration dependency and is also liveout.
    // For now only support one exit block and only trivial cross iteration
    // dependency.
    // TODO: Support peeled loops or flat CFG
    if (I->getNumUses() != 2 || I->getParent() != Reduce->getParent()) {
      LLVM_DEBUG(dbgs() << "LoopReassociate: cannot simplify it due to uses in "
                           "multiple blocks\n");
      return false;
    }

    // If it's cross-iteration dependency, make sure uses within the loop are
    // single-use [f]adds.
    for (User *U : I->users())
      if (auto *Inst = dyn_cast<Instruction>(U)) {
        if (L->contains(Inst)) {
          if (!isa<PHINode>(Inst) || GetFirstNonSupportedInstruction(Inst) != I) {
            LLVM_DEBUG(
                dbgs()
                << "LoopReassociate: cannot simplify it due to uses in non-PHI "
                   "outside of the loop\n");
            return false;
          }
        } else {
          // Outside use
          *LastUse = dyn_cast<PHINode>(Inst);
        }
      }
  } else {
    *LastUse = dyn_cast<PHINode>(I);
  }
  if (!*LastUse || (*LastUse)->getNumIncomingValues() != 1 ||
      L->contains(*LastUse))
    return false;

  LLVM_DEBUG(dbgs() << "LoopReassociate: can simplify that reduce\n");
  return true;
}

static void simplifyInLoopReduction(CallInst &Reduce, PHINode &LastUse,
                                    LoopInfo &LI) {
  const Loop *L = LI.getLoopFor(Reduce.getParent());
  const bool IsFPReduce = Reduce.getType()->isIEEELikeFPTy();
  const unsigned VecOpIdx = IsFPReduce ? 1 : 0;
  FastMathFlags FMF = IsFPReduce ? Reduce.getFastMathFlags() : FastMathFlags();
  Value *VecOp = Reduce.getOperand(VecOpIdx);
  VectorType *VTy = cast<VectorType>(VecOp->getType());
  Type *ScalarTy = VTy->getElementType();

  IRBuilder<> Builder(L->getLoopPreheader()->getTerminator());

  // Create an accumulator of identity values
  Value *Identity;
  if (IsFPReduce)
    Identity = FMF.noSignedZeros() ? ConstantFP::get(ScalarTy, 0.0L)
                                   : ConstantFP::get(ScalarTy, -0.0L);
  else
    Identity = ConstantInt::get(ScalarTy, 0);

  Value *InitAcc = Builder.CreateVectorSplat(VTy->getElementCount(), Identity);

  Builder.SetInsertPoint(L->getHeader()->getFirstInsertionPt());
  PHINode *Acc = Builder.CreatePHI(VTy, 2, "vector.accumulator");
  Acc->addIncoming(InitAcc, L->getLoopPreheader());

  Builder.SetInsertPoint(Reduce.getIterator());
  Value *AccUpdate = IsFPReduce ? Builder.CreateFAddFMF(VecOp, Acc, &Reduce)
                                : Builder.CreateAdd(VecOp, Acc);
  AccUpdate->setName("vector.accumulator.update");

  Acc->addIncoming(AccUpdate, cast<Instruction>(AccUpdate)->getParent());

  // In order to keep the loop in LCSSA form, create an extra PHI in exit block
  // for the accumulator.
  Builder.SetInsertPoint(&LastUse);
  PHINode *AccLCSSAPhi = Builder.CreatePHI(VTy, 1, "vector.accumulator.lcssa");
  AccLCSSAPhi->addIncoming(AccUpdate, LastUse.getIncomingBlock(0));

  // Instead of creating new vector.reduce, reuse existing one by modifying its
  // operands and move it in exit block.
  Reduce.replaceAllUsesWith(IsFPReduce ? Reduce.getOperand(0) : Identity);
  Reduce.setOperand(VecOpIdx, AccLCSSAPhi);
  if (IsFPReduce)
    Reduce.setOperand(0, Identity);

  Reduce.moveAfter(&LastUse);
  Builder.SetInsertPoint(++Reduce.getIterator());
  Value *UpdatedScalar = IsFPReduce
                             ? Builder.CreateFAddFMF(&LastUse, &Reduce, &Reduce)
                             : Builder.CreateAdd(&LastUse, &Reduce);

  LastUse.replaceAllUsesWith(UpdatedScalar);
  cast<Instruction>(UpdatedScalar)->setOperand(0, &LastUse);

  ++NumReassociatedReductions;
}

static bool reassociateLoop(Loop &L, LoopInfo &LI) {
  bool Changed = false;
  LoopBlocksRPO RPOT(&L);
  RPOT.perform(&LI);

  SmallVector<std::pair<CallInst *, PHINode *>> ReductionsToSimplify;
  for (BasicBlock *BB : RPOT) {
    for (Instruction &I : *BB) {
      PHINode *LastUse;
      if (canSimplifyInLoopReduction(&I, &LastUse, LI))
        ReductionsToSimplify.push_back({cast<CallInst>(&I), LastUse});
    }
  }

  for (auto &RP : ReductionsToSimplify) {
    simplifyInLoopReduction(*RP.first, *RP.second, LI);
    Changed = true;
  }

  return Changed;
}

PreservedAnalyses
SiFiveLoopReassociatePass::run(Loop &L, LoopAnalysisManager &AM,
                               LoopStandardAnalysisResults &AR,
                               LPMUpdater &Updater) {
  if (!EnableLoopReassociate)
    return PreservedAnalyses::all();

  if (!reassociateLoop(L, AR.LI))
    return PreservedAnalyses::all();

  LLVM_DEBUG(dbgs() << "LoopReassociate: reassociated reduction in "
                    << *L.getHeader()->getParent() << " function in loop " << L
                    << '\n');

  auto PA = getLoopPassPreservedAnalyses();
  PA.preserveSet<CFGAnalyses>();
  return PA;
}

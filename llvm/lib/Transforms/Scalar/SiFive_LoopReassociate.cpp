// The pass performs reassociation of instructions across loop.
// Currently the only optimization implemented in the pass hoists reduction
// computation out when it's possible:
//
//  for i = 0, N {
//    %r = phi %init, %r.next
//    ...
//    %red = vector.reduce ...
//
//    %r.next = add %red, %r
//  }
//  %r.lcssa = phi %r.next
//  <use-of-r.lcssa>
//
//===----------------------------------------------------------------------===//
